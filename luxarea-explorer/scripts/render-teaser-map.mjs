// Renders the home page's Residence Finder teaser map: real map data
// (OpenFreeMap / OpenStreetMap), recoloured in Luxarea's palette, saved as an
// image so the home page loads no map library at all. Pins are drawn on top
// in the browser from the listings, using the bounds saved here.
//
// Usage (needs network access to tiles.openfreemap.org):
//   node scripts/render-teaser-map.mjs
// Re-run only if the area or the style should change.
import { createRequire } from 'node:module'
// Playwright may be installed globally (as in CI images), so resolve it with require.
const { chromium } = createRequire(import.meta.url)('playwright')
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { resolve, join } from 'node:path'
import { tmpdir } from 'node:os'
const PNG = join(tmpdir(), 'luxarea-teaser-map.png')

const AREA = { west: 72.70, east: 73.0, south: 18.69, north: 19.13 } // Juhu to Kihim
const W = 440
const H = 680
const SCALE = 2

const style = await (await fetch('https://tiles.openfreemap.org/styles/positron')).json()
const C = {
  land: '#1b3331',
  water: '#0e2422',
  green: '#1f3a37',
  built: '#1e3835',
  building: '#22403c',
  road: 'rgba(223, 193, 156, 0.09)',
  major: 'rgba(223, 193, 156, 0.15)',
  motorway: 'rgba(223, 193, 156, 0.24)',
  rail: 'rgba(239, 233, 220, 0.07)',
  label: '#9fb2ac',
  waterLabel: '#6f8b87',
}
// Places only: no forts, reefs or rocks.
const keepSymbols = new Set(['label_city', 'label_city_capital', 'label_town', 'label_village'])
style.layers = style.layers.filter((l) => !l.id.startsWith('boundary') && !(l.type === 'symbol' && !keepSymbols.has(l.id)))
for (const l of style.layers) {
  const p = (l.paint ??= {})
  if (l.id === 'background') p['background-color'] = C.land
  else if (l.id === 'water') p['fill-color'] = C.water
  else if (l.id === 'waterway') p['line-color'] = C.water
  else if (['park', 'landcover_wood'].includes(l.id)) { p['fill-color'] = C.green; p['fill-opacity'] = 1 }
  else if (l.id === 'landuse_residential') { p['fill-color'] = C.built; p['fill-opacity'] = 1 }
  else if (l.id === 'building') { p['fill-color'] = C.building; p['fill-outline-color'] = C.building }
  else if (l.id.startsWith('aeroway')) { if (l.type === 'fill') p['fill-color'] = C.built; else p['line-color'] = C.road }
  else if (l.type === 'line' && l.id.includes('casing')) p['line-color'] = 'rgba(0,0,0,0)'
  else if (l.type === 'line' && l.id.includes('motorway')) p['line-color'] = C.motorway
  else if (l.type === 'line' && l.id.includes('major')) p['line-color'] = C.major
  else if (l.type === 'line' && l.id.startsWith('railway')) p['line-color'] = C.rail
  else if (l.type === 'line') p['line-color'] = C.road
  else if (l.type === 'fill') p['fill-color'] = C.built
  if (l.type === 'symbol') {
    p['text-color'] = l.id.startsWith('water') ? C.waterLabel : C.label
    p['text-halo-color'] = l.id.startsWith('water') ? C.water : C.land
    p['text-halo-width'] = 1.2
  }
}

const mlJs = readFileSync(resolve('node_modules/maplibre-gl/dist/maplibre-gl.js'), 'utf-8')
const mlCss = readFileSync(resolve('node_modules/maplibre-gl/dist/maplibre-gl.css'), 'utf-8')
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: SCALE })
await page.setContent(`<!doctype html><html><head><style>${mlCss} html,body,#m{margin:0;width:${W}px;height:${H}px} .maplibregl-ctrl-bottom-right,.maplibregl-ctrl-bottom-left{display:none}</style></head><body><div id="m"></div></body></html>`)
await page.addScriptTag({ content: mlJs })
const bounds = await page.evaluate(({ style, AREA }) => new Promise((resolve) => {
  // eslint-disable-next-line no-undef
  const map = new maplibregl.Map({ container: 'm', style, bounds: [[AREA.west, AREA.south], [AREA.east, AREA.north]], fitBoundsOptions: { padding: 0 }, interactive: false, attributionControl: false, fadeDuration: 0, preserveDrawingBuffer: true })
  map.once('idle', () => {
    const b = map.getBounds()
    resolve({ west: b.getWest(), east: b.getEast(), south: b.getSouth(), north: b.getNorth() })
  })
}), { style, AREA })
await page.waitForTimeout(500)
mkdirSync('public/maps', { recursive: true })
await page.screenshot({ path: PNG, clip: { x: 0, y: 0, width: W, height: H } })
// Compressed copy the site serves (cwebp ships with most systems; fall back to the PNG otherwise).
try {
  const { execFileSync } = await import('node:child_process')
  execFileSync('cwebp', ['-q', '82', '-quiet', PNG, '-o', 'public/maps/teaser-mumbai.webp'])
} catch {
  console.warn(`cwebp not found: convert ${PNG} to public/maps/teaser-mumbai.webp by hand`)
}
await browser.close()

writeFileSync('src/content/teaserMap.ts', `// Generated by scripts/render-teaser-map.mjs. Map data © OpenStreetMap contributors, tiles OpenFreeMap.
export const TEASER_MAP = ${JSON.stringify({ src: '/maps/teaser-mumbai.webp', width: W, height: H, bounds }, null, 2)} as const

const mercY = (lat: number) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))

/** Pixel position of a point on the teaser image, or null if it's outside the map. */
export function projectTeaser(lat: number, lng: number): { x: number; y: number } | null {
  const b = TEASER_MAP.bounds
  if (lat < b.south || lat > b.north || lng < b.west || lng > b.east) return null
  const x = ((lng - b.west) / (b.east - b.west)) * TEASER_MAP.width
  const y = ((mercY(b.north) - mercY(lat)) / (mercY(b.north) - mercY(b.south))) * TEASER_MAP.height
  return { x, y }
}
`)
console.log('bounds', bounds)
